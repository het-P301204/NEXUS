import { Link, useParams } from 'react-router'
import { motion } from 'motion/react'
import { ArrowLeft, Download, FileCode2, FileJson, Printer } from 'lucide-react'
import { download } from '../../lib/client/api.ts'
import { useCase, useReport, useUsers } from '../../lib/client/queries.ts'
import { short, stamp } from '../../lib/client/format.ts'
import { Button, Hash, Ident, SkeletonPage, cx } from '../../components/ui/primitives.tsx'
import { StageBadge } from '../../components/ui/status.tsx'
import { ErrorState, Notice } from '../../components/ui/feedback.tsx'
import { ReportActions, Stepper } from '../../components/reports/Workflow.tsx'

/**
 * The report preview renders the frozen content of one version as a printed
 * document: paper, numbered sections, the content hash in the header. Every
 * value is rendered as text by React; the content never carries markup.
 */
export function ReportDetail() {
  const { id = '' } = useParams()
  const q = useReport(id)
  const users = useUsers()
  const caseQ = useCase(q.data?.report.caseId ?? '')
  if (q.isError) return <ErrorState error={q.error} onRetry={() => void q.refetch()} />
  if (!q.data) return <SkeletonPage />
  const { report, transitions, reviews, versions, latestOfKind, approval } = q.data
  const name = (uid: string) => (uid === 'system' ? 'NEXUS (policy)' : (users.data?.find((u) => u.id === uid)?.name ?? uid))
  const c = report.content
  const decisionAnalyst = caseQ.data?.bundle.decisions.find((d) => d.id === report.decisionId)?.analystId ?? null
  const base = `${report.caseId}-${report.kind.toLowerCase()}-v${report.major}.${report.minor}`

  return (
    <div className="min-w-0">
      <div className="no-print mb-8 flex flex-wrap items-center justify-between gap-3">
        <Link to={`/cases/${report.caseId}?tab=report`} className="inline-flex items-center gap-1.5 text-sm text-ink-3 hover:text-ink">
          <ArrowLeft className="h-4 w-4" /> {report.caseId}
        </Link>
        <div className="flex flex-wrap gap-2">
          <Button size="sm" icon={<Printer className="h-3.5 w-3.5" />} onClick={() => window.print()}>
            Print
          </Button>
          <Button size="sm" icon={<Download className="h-3.5 w-3.5" />} onClick={() => void download(`/api/reports/${report.id}/export?format=html`, `${base}.html`)}>
            Export HTML
          </Button>
          <Button size="sm" icon={<FileCode2 className="h-3.5 w-3.5" />} onClick={() => void download(`/api/reports/${report.id}/export?format=md`, `${base}.md`)}>
            Markdown
          </Button>
          <Button size="sm" icon={<FileJson className="h-3.5 w-3.5" />} onClick={() => void download(`/api/reports/${report.id}/export?format=json`, `${base}.json`)}>
            JSON
          </Button>
        </div>
      </div>

      <div className="grid min-w-0 gap-10 2xl:grid-cols-[minmax(0,1fr)_340px]">
        <motion.article
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.45, ease: [0.22, 1, 0.36, 1] }}
          className="print-sheet mx-auto w-full min-w-0 max-w-[880px] rounded-xl bg-paper px-6 py-10 text-paper-ink shadow-overlay sm:px-14 sm:py-14"
          aria-label="Report preview"
        >
          <header className="border-b-2 border-paper-ink pb-7">
            <div className="font-mono text-[10.5px] font-semibold uppercase tracking-[0.16em] text-paper-2">
              {c.organization} · {report.caseId} · Report v{report.major}.{report.minor}
            </div>
            <h1 className="mt-4 text-3xl font-medium tracking-tight">{c.heading}</h1>
            <p className="mt-1.5 text-md text-paper-2">{c.subheading}</p>
            <dl className="mt-7 grid gap-x-8 gap-y-3 text-[12.5px] sm:grid-cols-2">
              {[
                ['Generated', stamp(report.generatedAt)],
                ['Generated by', name(report.generatedBy)],
                ['Rule set', report.ruleSetVersion],
                ['Stage', report.stage.replace(/_/g, ' ')],
                ['Case status at generation', report.caseStatus.replace(/_/g, ' ')],
                ['Evidence state', `${report.evidenceCount} items · ${report.evidenceStateHash.slice(0, 16)}`],
              ].map(([k, v]) => (
                <div key={k} className="min-w-0">
                  <dt className="font-mono text-[9.5px] font-semibold uppercase tracking-[0.12em] text-paper-2">{k}</dt>
                  <dd className="mt-0.5 [overflow-wrap:anywhere]">{v}</dd>
                </div>
              ))}
              <div className="min-w-0 sm:col-span-2">
                <dt className="font-mono text-[9.5px] font-semibold uppercase tracking-[0.12em] text-paper-2">Content hash (SHA-256)</dt>
                <dd className="mt-0.5 font-mono text-[11.5px] [overflow-wrap:anywhere]">{report.contentHash}</dd>
              </div>
            </dl>
            {report.submissionReference && (
              <div className="mt-5 inline-block rounded border border-paper-line px-3 py-1.5 font-mono text-[11px]">SIMULATED SUBMISSION · {report.submissionReference}</div>
            )}
          </header>

          {c.sections.map((s, i) => (
            <section key={s.id} className="mt-10 min-w-0 break-inside-avoid-page">
              <h2 className="flex items-baseline gap-3 text-[15px] font-semibold">
                <span className="font-mono text-[11px] text-paper-2">{String(i + 1).padStart(2, '0')}</span>
                {s.title}
              </h2>
              <div className="mt-3 space-y-2.5">
                {s.paragraphs.map((p, k) => (
                  <p key={k} className="text-[13.5px] leading-relaxed [overflow-wrap:anywhere]">
                    {p}
                  </p>
                ))}
              </div>
              {s.facts && s.facts.length > 0 && (
                <dl className="mt-4 grid gap-x-6 gap-y-2 text-[13px] sm:grid-cols-[210px_minmax(0,1fr)]">
                  {s.facts.map(([k, v]) => (
                    <div key={k} className="contents">
                      <dt className="text-paper-2">{k}</dt>
                      <dd className="min-w-0 [overflow-wrap:anywhere]">{v}</dd>
                    </div>
                  ))}
                </dl>
              )}
              {s.table && (
                <div className="mt-4 overflow-x-auto">
                  <table className="w-full min-w-[520px] border-collapse text-[12px]">
                    <thead>
                      <tr>
                        {s.table.columns.map((col) => (
                          <th key={col} className="border-b border-paper-line py-1.5 pr-3 text-left font-mono text-[9.5px] font-semibold uppercase tracking-[0.08em] text-paper-2">
                            {col}
                          </th>
                        ))}
                      </tr>
                    </thead>
                    <tbody>
                      {s.table.rows.map((row, r) => (
                        <tr key={r} className="border-b border-paper-line/60 align-top">
                          {row.map((cell, k) => (
                            <td key={k} className={cx('py-1.5 pr-3 [overflow-wrap:anywhere]', /^[0-9a-f]{24,}$/.test(cell) && 'font-mono text-[10.5px]')}>
                              {cell}
                            </td>
                          ))}
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              )}
            </section>
          ))}
          <footer className="mt-14 border-t border-paper-line pt-4 text-[11px] leading-relaxed text-paper-2">{c.disclaimer}</footer>
        </motion.article>

        <aside className="no-print min-w-0 space-y-8">
          <section aria-label="Workflow">
            <div className="mb-3 flex items-center justify-between">
              <div className="micro">Submission workflow</div>
              <StageBadge stage={report.stage} size="sm" />
            </div>
            <Stepper stage={report.stage} kind={report.kind} />
            <div className="mt-5">
              <ReportActions report={report} reviews={reviews} transitions={transitions} decisionAnalystId={decisionAnalyst} canWriteCase={!!caseQ.data?.canWrite} latest={latestOfKind} />
            </div>
            <p className="mt-3 text-xs text-ink-3">Policy: {approval.policy}</p>
          </section>
          {!latestOfKind && <Notice tone="amber">A newer version of this report exists. This version is kept for the record.</Notice>}
          <section aria-label="Versions">
            <div className="micro mb-3">Versions</div>
            <ul className="space-y-1.5">
              {[...versions].reverse().map((v) => (
                <li key={v.id}>
                  <Link to={`/reports/${v.id}`} className={cx('flex items-center justify-between gap-3 rounded-md px-2.5 py-2 text-sm transition-colors hover:bg-s2', v.id === report.id && 'bg-s3')}>
                    <span className="mono text-ink">
                      v{v.major}.{v.minor}
                    </span>
                    <span className="mono text-[11px] text-ink-3">{short(v.generatedAt)}</span>
                    <StageBadge stage={v.stage} size="sm" />
                  </Link>
                </li>
              ))}
            </ul>
          </section>
          <section aria-label="History">
            <div className="micro mb-3">Stage history</div>
            {transitions.length === 0 ? (
              <p className="text-xs text-ink-3">Draft since generation.</p>
            ) : (
              <ol className="relative space-y-3 border-l border-line-strong pl-4">
                {transitions.map((t) => (
                  <li key={t.id} className="relative text-xs">
                    <span className="absolute -left-[20.5px] top-1 h-2 w-2 rounded-full border border-line-bright bg-s1" />
                    <div className="text-ink">
                      {t.from.replace(/_/g, ' ').toLowerCase()} → {t.to.replace(/_/g, ' ').toLowerCase()}
                    </div>
                    <div className="text-ink-3">
                      {name(t.actorId)} · <span className="mono">{short(t.at)}</span>
                    </div>
                    {t.note && <div className="mt-0.5 text-ink-3">{t.note}</div>}
                  </li>
                ))}
              </ol>
            )}
          </section>
          {reviews.length > 0 && (
            <section aria-label="Reviews">
              <div className="micro mb-3">Reviews</div>
              <ul className="space-y-3">
                {reviews.map((r) => (
                  <li key={r.id} className="text-xs">
                    <span className={cx('micro', r.action === 'APPROVE' ? 'text-green' : 'text-amber')}>{r.action.replace(/_/g, ' ')}</span> <span className="text-ink">{name(r.reviewerId)}</span> <span className="mono text-ink-3">{short(r.createdAt)}</span>
                    {r.comment && <p className="mt-0.5 text-ink-2">{r.comment}</p>}
                  </li>
                ))}
              </ul>
            </section>
          )}
          <section aria-label="Integrity" className="text-xs text-ink-3">
            <div className="micro mb-2">Integrity</div>
            <Hash value={report.contentHash} length={14} />
            <p className="mt-1.5">SHA-256 over the canonical JSON of the content above. The exported HTML, Markdown and JSON carry the same hash.</p>
            <Ident dim className="mt-2 block text-[11px]">
              {report.id}
            </Ident>
          </section>
        </aside>
      </div>
    </div>
  )
}
